package ai.nanosamurai.workflowrunner.llm;

import com.fasterxml.jackson.databind.ObjectMapper;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Local smoke-test stub that replaces every LLM provider.
 *
 * Security:
 * - Must not perform any network calls.
 * - Must not log prompts or transcript bodies.
 */
public final class StubLlmClient implements LlmClient {

    private final ObjectMapper objectMapper;

    public StubLlmClient(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    @Override
    public LlmResponse invoke(LlmRequest request) throws Exception {
        String modelId = request == null ? null : request.modelId();
        String userPrompt = request == null ? "" : (request.userPrompt() == null ? "" : request.userPrompt());
        int promptLen = userPrompt.length();

        Map<String, Object> json = new LinkedHashMap<>();
        json.put("stub", true);
        json.put("model_id", modelId);
        json.put("user_prompt_len", promptLen);

        // Keep output deterministic and small.
        String markdown = "# Stub workflow result\n\n"
                          + "This result was generated by a local stub (no model call).\n\n"
                          + "- model_id: " + (modelId == null ? "" : modelId) + "\n"
                          + "- user_prompt_len: " + promptLen + "\n";

        Map<String, Object> envelope = new LinkedHashMap<>();
        envelope.put("markdown", markdown);
        envelope.put("json", json);

        String resp = objectMapper.writeValueAsString(envelope);
        // Token counts are best-effort; keep them null for stub.
        return new LlmResponse(resp, null, null);
    }
}
